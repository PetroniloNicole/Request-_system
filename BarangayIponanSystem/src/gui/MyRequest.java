    private Timer refreshTimer;
private void loadMyRequests() {
refreshTimer = new Timer(5000, e -> loadMyRequests());
refreshTimer.start();

addWindowListener(new java.awt.event.WindowAdapter() {
    @Override
    public void windowClosed(java.awt.event.WindowEvent e) {
        if (refreshTimer != null) {
            refreshTimer.stop();
        }
    }
});

    DefaultTableModel model =
            (DefaultTableModel) tblMyRequest.getModel();

    model.setRowCount(0);

    String sql = "SELECT request_id, service_type, purpose, "
               + "status, created_at "
               + "FROM service_requests "
               + "WHERE username = ? "
               + "ORDER BY created_at DESC";

    try (Connection conn = Database.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, loggedInUsername);

        try (ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("request_id"),
                    rs.getString("service_type"),
                    rs.getString("purpose"),
                    rs.getString("status"),
                    rs.getTimestamp("created_at")
                });
                lblRequestCount.setText(
        "Total Requests: " + model.getRowCount()
);
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Unable to load your requests.\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

private void colorStatusColumn() {

    DefaultTableCellRenderer renderer =
            new DefaultTableCellRenderer() {

        @Override
        public java.awt.Component getTableCellRendererComponent(
                JTable table,
                Object value,
                boolean isSelected,
                boolean hasFocus,
                int row,
                int column) {

            java.awt.Component component =
                    super.getTableCellRendererComponent(
                            table, value, isSelected, hasFocus, row, column
                    );

            if (!isSelected && value != null) {
                String status = value.toString();

                if (status.equalsIgnoreCase("PENDING")) {
                    component.setForeground(new Color(200, 120, 0));
                } else if (status.equalsIgnoreCase("APPROVED")) {
                    component.setForeground(new Color(0, 130, 60));
                } else if (status.equalsIgnoreCase("REJECTED")) {
                    component.setForeground(Color.RED);
                } else {
                    component.setForeground(Color.BLACK);
                }
            }

            return component;
        }
    };

    tblMyRequest.getColumnModel()
            .getColumn(3)
            .setCellRenderer(renderer);
}


