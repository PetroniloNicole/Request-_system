    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
       
String username = txtUsername.getText().trim();
String password = new String(txtPassword.getPassword());

if (username.isEmpty() || password.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Please enter your username and password.",
        "Missing Information",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}

String sql = "SELECT username, password_hash, role "
           + "FROM users WHERE username = ?";

try (Connection conn = Database.getConnection();
     PreparedStatement pst = conn.prepareStatement(sql)) {

    pst.setString(1, username);

    try (ResultSet rs = pst.executeQuery()) {

        if (rs.next()) {
            String storedHash = rs.getString("password_hash");
            String enteredHash = sha256(password);

            if (storedHash != null
                    && storedHash.equalsIgnoreCase(enteredHash)) {

                String role = rs.getString("role");
                
                MainFrame dashboard = new MainFrame(username,role);
                    dashboard.setLocationRelativeTo(null);
                      dashboard.setVisible(true);
                      this.dispose();
                      
                JOptionPane.showMessageDialog(
                    this,
                    "Login successful! Welcome, " + username + "."
                ); 

            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "Incorrect username or password.",
                    "Login Failed",
                    JOptionPane.ERROR_MESSAGE
                );
            }

        } else {
            JOptionPane.showMessageDialog(
                this,
                "Incorrect username or password.",
                "Login Failed",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this,
        "Login error: " + e.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE
    );
}

    }//GEN-LAST:event_btnLoginActionPerformed

    private void btnSignUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignUpActionPerformed


    String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword());
    String confirmPassword =
            new String(txtPassword.getPassword());

    if (username.isEmpty() || password.isEmpty()
            || confirmPassword.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields.",
            "Incomplete Information",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if (username.length() < 4) {
        JOptionPane.showMessageDialog(
            this,
            "Username must be at least 4 characters.",
            "Invalid Username",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if (password.length() < 8) {
        JOptionPane.showMessageDialog(
            this,
            "Password must be at least 8 characters.",
            "Invalid Password",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    if (!password.equals(confirmPassword)) {
        JOptionPane.showMessageDialog(
            this,
            "Passwords do not match.",
            "Password Error",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "INSERT INTO users "
            + "(username, password_hash, role) "
            + "VALUES (?, ?, 'RESIDENT')";

    try (Connection conn = Database.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, username);
        pst.setString(2, hashPassword(password));

        pst.executeUpdate();

        JOptionPane.showMessageDialog(
            this,
            "Account created successfully! You can now log in."
        );

        new LoginFrame().setVisible(true);
        this.dispose();

    } catch (java.sql.SQLIntegrityConstraintViolationException ex) {
        JOptionPane.showMessageDialog(
            this,
            "That username already exists. Please choose another.",
            "Username Taken",
            JOptionPane.WARNING_MESSAGE
        );

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(
            this,
            "Unable to create account: " + ex.getMessage(),
            "Sign Up Error",
            JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnSignUpActionPerformed

