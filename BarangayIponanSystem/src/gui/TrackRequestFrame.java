    private void btnCheckStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckStatusActionPerformed
       String requestIDText = txtRequestID.getText().trim();

if (requestIDText.isEmpty()) {
    JOptionPane.showMessageDialog(
            this,
            "Please enter your Request ID.",
            "Missing Request ID",
            JOptionPane.WARNING_MESSAGE
    );
    return;
}

int requestID;

try {
    requestID = Integer.parseInt(requestIDText);

    if (requestID <= 0) {
        throw new NumberFormatException();
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(
            this,
            "Please enter a valid numeric Request ID.",
            "Invalid Request ID",
            JOptionPane.WARNING_MESSAGE
    );
    return;
}

String sql = "SELECT service_type, status, created_at "
           + "FROM service_requests "
           + "WHERE request_id = ? AND username = ?";

try (Connection conn = Database.getConnection();
     PreparedStatement pst = conn.prepareStatement(sql)) {

    pst.setInt(1, requestID);
    pst.setString(2, loggedInUsername);

    try (ResultSet rs = pst.executeQuery()) {
        
    

    if (rs.next()) {

        String status = rs.getString("status");
        String message;

        if ("PENDING".equalsIgnoreCase(status)) {
            message = "Your request is waiting for review.";
        } else if ("APPROVED".equalsIgnoreCase(status)) {
            message = "Your request has been approved!";
        } else if ("REJECTED".equalsIgnoreCase(status)) {
            message = "Your request has been rejected. Please contact the barangay office for assistance.";
        } else {
            message = "Current status: " + status;
        }

        lblStatus.setText(
                "<html>"
                + "<b>Service:</b> " + rs.getString("service_type")
                + "<br><b>Status:</b> " + status
                + "<br><b>Date Submitted:</b> " + rs.getString("created_at")
                + "<br><br>" + message
                + "</html>"
        );

    } else {
        lblStatus.setText(
                "Request not found. Please check your Request ID."
        );
    }
    }
} catch (SQLException e) {
    JOptionPane.showMessageDialog(
            this,
            "Unable to check request status. Please try again.\n"
            + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
    );
}

    }//GEN-LAST:event_btnCheckStatusActionPerformed

