    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed

    btnSubmit.setEnabled(false);

    try {
        String firstname = txtFirstname.getText().trim();
        String lastname = txtLastname.getText().trim();
        String middlename = txtMiddlename.getText().trim();
        String birthdate = txtBirthdate.getText().trim();
        String address = txtAddress.getText().trim();
        String contact = txtContact.getText().trim();
        String email = txtEmail.getText().trim();
        String occupation = txtOccupation.getText().trim();
        String idType = cmbIDType.getSelectedItem().toString();
        String idNumber = txtIDNumber.getText().trim();
        String serviceType = cmbServiceType.getSelectedItem().toString();
        String purpose = txtPurpose.getText().trim();
        String civilStatus = cmbCivilStatus.getSelectedItem().toString();

        String gender = "";
        if (rdoMale.isSelected()) {
            gender = "Male";
        } else if (rdoFemale.isSelected()) {
            gender = "Female";
        } else if (rdoOthers.isSelected()) {
            gender = "Others";
        }

        String paymentMethod = "";
        if (rdoGcash.isSelected()) {
            paymentMethod = "GCash";
        } else if (rdoCash.isSelected()) {
            paymentMethod = "Cash";
        }

        // Validate required fields
        if (firstname.isEmpty() || lastname.isEmpty()
                || birthdate.isEmpty() || address.isEmpty()
                || purpose.isEmpty()) {

            JOptionPane.showMessageDialog(
                this,
                "Please complete all required fields.",
                "Missing Information",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (gender.isEmpty()) {
            JOptionPane.showMessageDialog(
                this, "Please select a gender."
            );
            return;
        }

        if (serviceType.equals("Select")) {
            JOptionPane.showMessageDialog(
                this, "Please select a service type."
            );
            return;
        }

        if (!birthdate.matches("\\d{4}-\\d{2}-\\d{2}")) {
            JOptionPane.showMessageDialog(
                this,
                "Enter birthdate using yyyy-MM-dd format, "
                + "for example 2005-09-15."
            );
            return;
        }

        if (loggedInUsername == null
                || loggedInUsername.trim().isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Login username is missing. Please log in again."
            );
            return;
        }

        // Save the request
        

String summary =
    "Please review your service request:\n\n"
    + "Resident: " + firstname + " " + middlename
        + " " + lastname + "\n"
    + "Birthdate: " + birthdate + "\n"
    + "Address: " + address + "\n"
    + "Gender: " + gender + "\n"
    + "Service Type: " + serviceType + "\n"
    + "Submission Date: "
    + new java.text.SimpleDateFormat("yyyy-MM-dd HH:mm")
        .format(new java.util.Date()) + "\n"
    + "Purpose: " + purpose + "\n"
    + "Payment Method: "
        + (paymentMethod.isEmpty() ? "Not selected" : paymentMethod)
    + "\n\nDo you want to submit this request?";

int confirm = JOptionPane.showConfirmDialog(
    this,
    summary,
    "Review Service Request",
    JOptionPane.YES_NO_OPTION,
    JOptionPane.QUESTION_MESSAGE
);

if (confirm != JOptionPane.YES_OPTION) {
    return;
}


        RequestService requestService = new RequestService();
         
int requestId = requestService.saveRequestAndGetId(
        loggedInUsername,
        txtFirstname.getText().trim(),
        txtLastname.getText().trim(),
        txtMiddlename.getText().trim(),
        txtBirthdate.getText().trim(),
        gender,
        txtAddress.getText().trim(),
        cmbCivilStatus.getSelectedItem().toString(),
        txtContact.getText().trim(),
        txtEmail.getText().trim(),
        txtOccupation.getText().trim(),
        cmbIDType.getSelectedItem().toString(),
        txtIDNumber.getText().trim(),
        cmbServiceType.getSelectedItem().toString(),
        txtPurpose.getText().trim(),
        chkValidID.isSelected(),
        chkProofAddress.isSelected(),
        chkOtherDocuments.isSelected(),
        paymentMethod
);

if (requestId > 0) {
    String receipt =
            "REQUEST SUBMITTED SUCCESSFULLY!\n\n"
            + "Request ID: " + requestId + "\n"
            + "Resident: "
            + txtFirstname.getText().trim() + " "
            + txtLastname.getText().trim() + "\n"
            + "Service: "
            + cmbServiceType.getSelectedItem().toString() + "\n"
            + "Status: PENDING\n\n"
            + "Please save your Request ID for tracking.";

    JOptionPane.showMessageDialog(
            this,
            receipt,
            "Request Receipt",
            JOptionPane.INFORMATION_MESSAGE
    );

    btnClearActionPerformed(null);
} else {
    JOptionPane.showMessageDialog(
            this,
            "The request could not be saved.",
            "Submission Failed",
            JOptionPane.ERROR_MESSAGE
    );
}

    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(
            this,
            "Invalid birthdate. Please use yyyy-MM-dd format."
        );

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Database error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        
          btnClearActionPerformed(null);

    } finally {
        // Always enable the Submit button again
    }

    }//GEN-LAST:event_btnSubmitActionPerformed

